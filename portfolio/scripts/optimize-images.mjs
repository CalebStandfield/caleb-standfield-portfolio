// Builds responsive WebP variants for every raster image under public/ and
// writes a manifest (dimensions + srcset) the app reads at render time.
//
// Usage: npm run images
// Needs `cwebp` (brew install webp) and macOS `sips`. Outputs are committed, so
// this only runs locally when images change, never on deploy.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");
const outDir = join(publicDir, "img");
const manifestPath = join(root, "src", "content", "images.generated.ts");

const WIDTHS = [480, 960, 1200, 1600]; // capped at the source width
const QUALITY = 88; // high enough that UI text in screenshots stays crisp
const SOURCE_EXT = new Set([".png", ".jpg", ".jpeg"]);
const SKIP = new Set(["og.png"]); // social card, crawlers want the original

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (path === outDir) return [];
    if (statSync(path).isDirectory()) return walk(path);
    return SOURCE_EXT.has(extname(name).toLowerCase()) && !SKIP.has(name)
      ? [path]
      : [];
  });
}

function dimensions(path) {
  const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", path], {
    encoding: "utf8",
  });
  const read = (key) => Number(out.match(new RegExp(`${key}: (\\d+)`))[1]);
  return { width: read("pixelWidth"), height: read("pixelHeight") };
}

// public path as the browser sees it, e.g. /blackjack/main.png
const toUrl = (path) => "/" + relative(publicDir, path).split(sep).join("/");

function encode(source, target, width) {
  const fresh =
    existsSync(target) && statSync(target).mtimeMs >= statSync(source).mtimeMs;
  if (fresh) return;
  mkdirSync(dirname(target), { recursive: true });
  execFileSync("cwebp", [
    "-quiet", "-q", String(QUALITY), "-m", "6", "-sharp_yuv", "-metadata", "none",
    "-resize", String(width), "0", source, "-o", target,
  ]);
}

const manifest = {};

for (const source of walk(publicDir).sort()) {
  const { width, height } = dimensions(source);
  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, width)))];
  const base = relative(publicDir, source).slice(0, -extname(source).length);

  const variants = widths.map((w) => {
    const target = join(outDir, `${base}-${w}.webp`);
    encode(source, target, w);
    return { url: toUrl(target), width: w };
  });

  manifest[toUrl(source)] = { width, height, variants };
}

writeFileSync(
  manifestPath,
  `// Generated by scripts/optimize-images.mjs (npm run images). Do not edit.

export type ImageVariant = { url: string; width: number };
export type ImageEntry = { width: number; height: number; variants: ImageVariant[] };

export const imageManifest: Record<string, ImageEntry> = ${JSON.stringify(manifest, null, 2)};
`,
);

console.log(`optimized ${Object.keys(manifest).length} images -> ${relative(root, outDir)}`);
